// Математика «проявки»: насколько фотография проявлена, 0 — розовый растр, 1 — цветной снимок.
// Здесь нет ни DOM, ни WebGL, поэтому всё проверяется тестами (tools/tests/progress.test.mjs).

/** Все настройки пресса, которые подбираются на глаз. Больше нигде чисел «по вкусу» нет. */
export const TUNING = {
    cellPlate: 5,              // шаг растра на пластинах, CSS-пиксели
    cellHero: 7,               // на первой полосе точки крупнее: кадр большой и смотрят на него издали
    angle: 45,                 // угол растра, градусы — как у одной краски в настоящей печати
    detail: 1,                 // на сколько ступеней тон резче ячейки растра: больше — подробнее, но точки менее круглые
    // Кривая печати на бумаге: степень (больше — светлее) и предел заливки. Предел чуть выше половины:
    // даже в самых тёмных местах точки лишь касаются друг друга, и снимок не превращается в розовое пятно
    tonePlate: [1.8, 0.62],
    toneHero: [1, 0.8],        // то же для светлых точек на тёмной плашке
    dprMax: 2,                 // плотнее рисовать незачем: точки и так крупнее пикселя
    areaMax: 2.5e6,            // предел площади одного холста, пиксели
    texturesMax: 8e6,          // сколько пикселей фотографий держим в видеопамяти
    margin: '30% 0px',         // пластину готовим заранее, за треть экрана до появления
    plateBand: [0.35, 0.9],    // доля пути от середины экрана к краю: до первой — цвет, после второй — растр
    heroBand: [0.1, 0.7],      // доля первой полосы, ушедшей вверх: от цвета до растра
    introMs: 1600,             // сколько длится проявка первой полосы после загрузки
    introLate: 1200,           // если пресс запустился позже (мс от начала загрузки), проявку не играем
    fadeFrom: 0.9,             // с этого прогресса холст тает и уступает место настоящему <img>
    // Стадии превращения внутри шейдера, в долях прогресса. Снимок проступает сквозь сами точки:
    // сплошной розовой плёнки поверх фотографии не бывает ни в один момент
    colour: [0.05, 0.5],       // точки из розовых становятся цветными — каждая показывает свой кусочек снимка
    grow: [0.2, 1],            // точки разрастаются, пока не закроют лист целиком
    soften: [0.3, 0.9],        // края точек при этом смягчаются
};

/** Зажимает число в отрезок 0…1. */
export function clamp01(x) {
    return x < 0 ? 0 : x > 1 ? 1 : x;
}

/** Плавная ступенька: 0 до a, 1 после b, между ними мягкий переход. */
export function smoothstep(a, b, x) {
    const t = clamp01((x - a) / (b - a));
    return t * t * (3 - 2 * t);
}

/**
 * Как близко к середине экрана пластина вообще может подойти: 0 — доходит до середины, ближе к 1 — остаётся у края.
 * Пластины в самом начале и в самом конце страницы до середины не докрутить, и без поправки
 * они навсегда остались бы растром.
 * top, height — положение на странице; vh — высота окна; maxScroll — насколько страница прокручивается.
 */
export function plateReach(top, height, vh, maxScroll) {
    const centre = top + height / 2;
    const best = Math.min(Math.max(centre - vh / 2, 0), Math.max(maxScroll, 0));
    return Math.min(Math.abs(centre - best - vh / 2) / (vh / 2), 0.98);
}

/**
 * Проявленность пластины. centreY — середина пластины относительно верха окна,
 * reach — результат plateReach().
 */
export function plateProgress(centreY, vh, reach) {
    const c = Math.abs(centreY - vh / 2) / (vh / 2);
    return 1 - smoothstep(TUNING.plateBand[0], TUNING.plateBand[1], (c - reach) / (1 - reach));
}

/** Проявка первой полосы после загрузки: медленно начинается и медленно заканчивается. */
export function introProgress(elapsed, duration) {
    const t = clamp01(elapsed / duration);
    return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(2 - 2 * t, 3) / 2;
}

/**
 * Проявленность первой полосы: не больше, чем успела проявка после загрузки,
 * и обратно в растр, когда полоса уходит вверх. bottom — нижний край кадра на странице.
 */
export function heroProgress(intro, scrollY, bottom) {
    const gone = bottom > 0 ? scrollY / bottom : 1;
    return Math.min(clamp01(intro), 1 - smoothstep(TUNING.heroBand[0], TUNING.heroBand[1], gone));
}

/** Непрозрачность холста: под конец он тает, и остаётся настоящая фотография под ним. */
export function canvasOpacity(p) {
    return 1 - clamp01((p - TUNING.fadeFrom) / (1 - TUNING.fadeFrom));
}
